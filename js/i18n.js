// 各語言對應的排版 locale 與 <html lang>
export const UI_LOCALE = {
  zh_TW: 'zh-Hant-TW', zh_CN: 'zh-Hans-CN', ja: 'ja-JP', ko: 'ko-KR', en: 'en-US',
};
const HTML_LANG = {
  zh_TW: 'zh-Hant', zh_CN: 'zh-Hans', ja: 'ja', ko: 'ko', en: 'en',
};

let current = 'zh_TW';

export function detectLang() {
  const l = (navigator.language || '').toLowerCase();
  if (l.startsWith('zh')) {
    return (l.includes('cn') || l.includes('sg') || l.includes('hans')) ? 'zh_CN' : 'zh_TW';
  }
  if (l.startsWith('ja')) return 'ja';
  if (l.startsWith('ko')) return 'ko';
  return 'en';
}

export function setLang(lang) {
  current = DICT[lang] ? lang : 'zh_TW';
  document.documentElement.lang = HTML_LANG[current] || 'en';
}

export function getLang() { return current; }

export function t(key) {
  return DICT[current][key] ?? DICT.zh_TW[key] ?? key;
}

// 套用到所有 data-i18n / data-i18n-ph 節點
export function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = t(el.dataset.i18n);
  });
  root.querySelectorAll('[data-i18n-ph]').forEach(el => {
    el.placeholder = t(el.dataset.i18nPh);
  });
}
